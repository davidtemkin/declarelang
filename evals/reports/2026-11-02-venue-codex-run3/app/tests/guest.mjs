export default async ({ drive, expect, page }) => {
  await drive.settleData();
  await expect(page.getByRole('button', {name:/Fri 13 Nov, 7:30pm/})).toBeVisible();
  const count = await page.evaluate(() => window.__declare.find('app').production.value.performances.length);
  await expect(count).toBe(20);
  await page.getByRole('button', {name:/Fri 13 Nov, 7:30pm/}).click();
  await drive.settleData();
  const seats = await page.evaluate(() => window.__declare.find('app').hall.seats().filter(s => s.seat.status === 'available' && s.row !== 'A').slice(0,2).map(s => ({id:s.id,name:`${s.section}, row ${s.row}, seat ${s.seat.number}`,price:s.priceCents,fee:s.feeCents})));
  for (const seat of seats) await page.getByRole('button', {name:seat.name, exact:true}).click();
  const subtotal = seats.reduce((n,s)=>n+s.price,0), total = seats.reduce((n,s)=>n+s.price+s.fee,0);
  await expect.text('app.dock', `2 seats · $${(subtotal/100).toFixed(2)}`);
  await page.getByRole('button',{name:'Continue →',exact:true}).click();
  await page.getByRole('button',{name:`Pay $${(total/100).toFixed(2)}`,exact:true}).click();
  await expect.request('POST', '/api/orders', {count:0});
  await expect(page.getByRole('textbox',{name:'Email address',exact:true})).toBeFocused();
  const fill = async (name,value) => page.getByRole('textbox',{name,exact:true}).fill(value);
  await fill('Email address','guest@example.com');
  await fill('Name on card','Guest Reader');
  await fill('Card number','4242424242424242');
  await expect(page.getByRole('textbox',{name:'Card number',exact:true})).toHaveValue('4242 4242 4242 4242');
  await fill('Expiry date','04/28');
  await page.getByLabel('Security code',{exact:true}).fill('123');
  await fill('Street address','27 Grove Street');
  await fill('City','San Francisco');
  await fill('Postal code','94103');
  await page.screenshot({path:'my-apps/venue/tests/checkout-desktop.png'});
  const pay = page.getByRole('button',{name:`Pay $${(total/100).toFixed(2)}`,exact:true});
  await pay.click();
  await drive.settleData();
  await expect.request('POST','/api/orders',{count:1,body:{email:'guest@example.com',seatIds:seats.map(s=>s.id)}});
  await expect.text('app.body.page.tickets','Sent to guest@example.com');
  await expect.visible('app.body.page.tickets.ticket');
  await expect(page.getByRole('img',{name:/Scannable ticket/})).toBeVisible();
  await page.getByRole('button',{name:'Next →',exact:true}).click();
  await expect.text('app.body.page.tickets.pager','2 of 2');
  await page.screenshot({path:'my-apps/venue/tests/ticket-desktop.png'});
};
