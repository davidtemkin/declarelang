export const device = { width: 390, height: 844, touch: true, deviceScaleFactor: 2 };
export default async ({ drive, expect, page }) => {
  await drive.settleData();
  await page.getByRole('button',{name:/Fri 13 Nov, 7:30pm/}).click();
  await drive.settleData();
  const seats = await page.evaluate(() => {
    const a = window.__declare.find('app');
    return ['ORCH','BALC'].map(key => a.hall.seats().find(s=>s.sectionKey===key && s.row==='A' && s.seat.status==='available')).map(s=>({id:s.id,key:s.sectionKey,name:`${s.section}, row ${s.row}, seat ${s.seat.number}`,section:s.section,price:s.priceCents,fee:s.feeCents}));
  });
  for (const seat of seats) {
    await page.getByRole('button',{name:new RegExp(`^${seat.section}, \\$`)}).click();
    await page.getByRole('button',{name:seat.name,exact:true}).click();
  }
  await expect.text('app.dock','2 seats · $115.00');
  await page.screenshot({path:'my-apps/venue/tests/selected-phone.png'});
  await page.getByRole('button',{name:'Continue →',exact:true}).click();
  await page.getByRole('textbox',{name:'Email address',exact:true}).fill('keep@example.com');
  await page.getByRole('textbox',{name:'Street address',exact:true}).fill('34 Preserved Street');
  await page.getByRole('main').getByRole('button',{name:'Sign in',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Sign in',exact:true});
  await dialog.getByRole('textbox',{name:'Email address',exact:true}).fill('ada@example.com');
  await dialog.getByLabel('Password',{exact:true}).fill('wrong');
  await expect(dialog.getByLabel('Password',{exact:true})).toHaveAttribute('type','password');
  await dialog.getByRole('button',{name:'Sign in',exact:true}).click();
  await drive.settleData();
  await expect(dialog).toContainText("That email and password don't match.");
  await dialog.getByLabel('Password',{exact:true}).fill('correct horse battery');
  await dialog.getByRole('checkbox',{name:'Show password',exact:true}).click();
  await expect(dialog.getByLabel('Password',{exact:true})).toHaveAttribute('type','text');
  await dialog.getByRole('button',{name:'Sign in',exact:true}).click();
  await drive.settleData();
  await expect(page.getByRole('button',{name:/Mastercard ending 4444.*expired/})).toBeDisabled();
  await expect(page.getByRole('button',{name:/Visa ending 4242/})).toHaveAttribute('aria-pressed','true');
  await page.getByLabel('Security code',{exact:true}).fill('000');
  await page.getByRole('button',{name:'Pay $126.00',exact:true}).dblclick();
  await drive.settleData();
  await expect.request('POST','/api/orders',{count:1,body:{payment:{savedCardId:'card_1',cvc:'000'},email:'keep@example.com'}});
  await expect.text('app.body.page.checkout','declined');
  await expect(page.getByLabel('Security code',{exact:true})).toHaveValue('');
  await page.getByRole('button',{name:'Use a new card',exact:true}).click();
  await expect(page.getByRole('textbox',{name:'Email address',exact:true})).toHaveValue('keep@example.com');
  await expect(page.getByRole('textbox',{name:'Street address',exact:true})).toHaveValue('34 Preserved Street');
  await expect(page.getByRole('textbox',{name:'Name on card',exact:true})).toHaveValue('Ada Lovelace');
  await page.getByRole('textbox',{name:'Card number',exact:true}).fill('378282246310005');
  await expect(page.getByRole('textbox',{name:'Card number',exact:true})).toHaveValue('3782 822463 10005');
  await page.getByRole('textbox',{name:'Expiry date',exact:true}).fill('13/28');
  await page.getByLabel('Security code',{exact:true}).fill('123');
  await page.getByRole('textbox',{name:'Postal code',exact:true}).fill('bad');
  await page.getByRole('textbox',{name:'City',exact:true}).focus();
  await expect.text('app.body.page.checkout','Enter a UK postal code');
  await page.getByRole('button',{name:'Pay $126.00',exact:true}).click();
  await expect.request('POST','/api/orders',{count:1});
  await page.getByRole('textbox',{name:'Expiry date',exact:true}).fill('04/28');
  await page.getByLabel('Security code',{exact:true}).fill('1234');
  await page.getByRole('textbox',{name:'Postal code',exact:true}).fill('SW1A 1AA');
  await page.getByRole('button',{name:'Pay $126.00',exact:true}).click();
  await drive.settleData();
  await expect.request('POST','/api/orders',{count:2});
  await expect(page.getByRole('textbox',{name:'Postal code',exact:true})).toBeFocused();
  await expect(page.getByRole('textbox',{name:'Postal code',exact:true})).toHaveAttribute('aria-invalid','true');
  await page.getByRole('textbox',{name:'Postal code',exact:true}).fill('WC1N 1AB');
  await page.getByLabel('Security code',{exact:true}).fill('1234');
  await page.getByRole('button',{name:'Pay $126.00',exact:true}).click();
  await drive.settleData();
  await expect.text('app.body.page.tickets','Sent to keep@example.com');
  await expect.request('POST','/api/orders',{count:3});
  await page.screenshot({path:'my-apps/venue/tests/ticket-phone.png'});
  await page.reload();
  await drive.settleData();
  await expect(page.getByRole('button',{name:'Sign out',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await drive.settleData();
  await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible();
};
