import { launch, slideBox, drag, api } from './common.mjs'
const { browser, page, errors } = await launch(1280, 800)
await page.goto('http://localhost:5173/')
await page.getByRole('button', { name: 'New presentation' }).first().click()
await page.waitForURL(/\/d\//)
await page.waitForTimeout(900)
await page.screenshot({ path: '/tmp/pf/w1.png' })
await page.keyboard.press('Escape')
const { at } = await slideBox(page)
await page.keyboard.press('r')
await drag(page, at(200, 200), at(600, 500))
await page.keyboard.press('Escape')
await page.mouse.move(at(400, 300).x, at(400, 300).y)
await page.mouse.move(at(401, 301).x, at(401, 301).y)
await page.waitForTimeout(200)
await page.screenshot({ path: '/tmp/pf/w2.png' })
// text click on empty and leave empty -> disappears, no undo step
await page.keyboard.press('t')
await page.mouse.click(at(800, 600).x, at(800, 600).y)
await page.waitForTimeout(100)
await page.keyboard.press('Escape')
const undoEnabled = await page.getByRole('button', { name: 'Undo' }).isEnabled()
console.log('text boxes after empty:', await page.locator('[aria-label=Slide] foreignObject').count(), 'undo enabled (rect step):', undoEnabled)
await page.keyboard.press('Meta+z')
console.log('after undo, shapes:', await page.locator('[aria-label=Slide] [data-element-id]').count())
console.log(errors.join('\n'))
await browser.close()
