import { launch, slideBox, drag, api } from './common.mjs'
const { browser, page, errors } = await launch()
const log = (...a) => console.log(...a)
const decks = await api('/api/decks')
const deck = decks.decks.find((d) => d.title === 'Quarterly review')
await page.goto('http://localhost:5173/d/' + deck.id)
await page.waitForTimeout(1000)
const { at } = await slideBox(page)
await page.keyboard.press('o')
await page.keyboard.down('Shift')
await drag(page, at(200, 480), at(300, 560))
await page.keyboard.up('Shift')
await page.keyboard.press('t')
await page.mouse.click(at(330, 530).x, at(330, 530).y)
await page.keyboard.type('Label')
await page.keyboard.press('Escape')
await page.keyboard.press('Escape')
await drag(page, at(150, 440), at(600, 640))
await page.keyboard.press('Meta+g')
await page.waitForTimeout(200)
await page.screenshot({ path: '/tmp/pf/t1.png' })
const sel = async () => (await page.locator('aside[aria-label=Inspector] h2').textContent())
log('after group:', await sel())
await drag(page, at(250, 530), at(450, 500))
await page.waitForTimeout(200)
await page.screenshot({ path: '/tmp/pf/t2.png' })
await page.keyboard.press('Meta+z')
log('after undo 1:', await sel())
await page.keyboard.press('Meta+z')
log('after undo 2:', await sel())
await page.waitForTimeout(200)
await page.screenshot({ path: '/tmp/pf/t3.png' })
// duplicate slide via menu
await page.getByRole('button', { name: 'Slide', exact: true }).click()
await page.getByRole('menuitem', { name: 'Duplicate slide' }).click()
await page.waitForTimeout(300)
// edit title on copy
await page.mouse.dblclick(at(640, 100).x, at(640, 100).y)
await page.keyboard.press('Meta+a')
await page.keyboard.type('Quarterly review: copy')
await page.keyboard.press('Escape')
await page.waitForTimeout(200)
// drag slide 2 above slide 1
const s2 = await page.getByRole('option', { name: 'Slide 2' }).boundingBox()
const s1 = await page.getByRole('option', { name: 'Slide 1' }).boundingBox()
await drag(page, { x: s2.x + s2.width / 2, y: s2.y + s2.height / 2 }, { x: s1.x + s1.width / 2, y: s1.y + 10 }, { steps: 20 })
await page.waitForTimeout(500)
await page.screenshot({ path: '/tmp/pf/t4.png' })
// present from start
await page.getByRole('option', { name: 'Slide 1' }).click()
await page.getByRole('button', { name: 'Present' }).click()
await page.waitForTimeout(500)
await page.screenshot({ path: '/tmp/pf/t5.png' })
await page.keyboard.press('ArrowRight')
await page.waitForTimeout(200)
await page.screenshot({ path: '/tmp/pf/t6.png' })
await page.keyboard.press('Escape')
await page.waitForTimeout(400)
log('current after present:', await page.locator('[role=option][aria-selected=true]').getAttribute('aria-label'))
await page.waitForTimeout(2500)
log('status:', await page.getByRole('status').first().textContent())
// colleague edits second slide
const d = await api('/api/decks/' + deck.id)
const second = await api('/api/slides/' + d.slideOrder[1])
log('server order', d.slideOrder, 'second slide title', second.elements[1]?.text?.content)
second.elements[1].text.content = 'Edited by a colleague'
const put = await api('/api/slides/' + second.id, { method: 'PUT', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ version: second.version, background: '#FFF6DB', elements: second.elements }) })
log('colleague put version', put.version)
await page.getByRole('option', { name: 'Slide 1' }).click()
await page.waitForTimeout(5000)
await page.getByRole('option', { name: 'Slide 2' }).click()
await page.waitForTimeout(1500)
await page.screenshot({ path: '/tmp/pf/t7.png' })
await page.getByRole('button', { name: 'Use their version' }).click()
await page.waitForTimeout(2500)
await page.screenshot({ path: '/tmp/pf/t8.png' })
log('status:', await page.getByRole('status').first().textContent())
log(errors.join('\n'))
await browser.close()
