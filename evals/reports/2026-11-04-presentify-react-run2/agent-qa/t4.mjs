import { launch, slideBox, drag, api } from './common.mjs'
const { browser, page, errors } = await launch()
const log = (...a) => console.log(...a)
await page.goto('http://localhost:5173/')
await page.waitForTimeout(800)
await page.getByRole('button', { name: 'More actions for Interaction test' }).click()
await page.getByRole('menuitem', { name: 'Rename' }).click()
await page.keyboard.type('Renamed deck')
await page.keyboard.press('Enter')
await page.waitForTimeout(1200)
log('renamed:', (await api('/api/decks')).decks.map((d) => d.title).includes('Renamed deck'))
await page.getByRole('button', { name: 'More actions for Renamed deck' }).click()
await page.getByRole('menuitem', { name: 'Delete…' }).click()
await page.waitForTimeout(300)
await page.screenshot({ path: '/tmp/pf/v1.png' })
await page.getByRole('button', { name: 'Delete presentation' }).click()
await page.waitForTimeout(1200)
log('deleted:', !(await api('/api/decks')).decks.map((d) => d.title).includes('Renamed deck'))
// group dbl-click in seeded deck 1 slide 1 (e5 group of waves) -- open, dblclick on wave, check selection is child, then escape without changes
await page.getByRole('button', { name: 'Open Field notes from the coast' }).click()
await page.waitForTimeout(1200)
const { at } = await slideBox(page)
await page.mouse.click(at(1100, 700).x, at(1100, 700).y)
log('click:', await page.locator('aside[aria-label=Inspector] h2').textContent())
await page.mouse.dblclick(at(1100, 700).x, at(1100, 700).y)
log('dblclick:', await page.locator('aside[aria-label=Inspector] h2').textContent())
await page.screenshot({ path: '/tmp/pf/v2.png' })
await page.keyboard.press('Escape')
log('esc:', await page.locator('aside[aria-label=Inspector] h2').textContent())
// hover tooltip
await page.getByRole('button', { name: 'Rectangle', exact: true }).hover()
await page.waitForTimeout(800)
await page.screenshot({ path: '/tmp/pf/v3.png', clip: { x: 400, y: 50, width: 600, height: 120 } })
// right click context menu
await page.mouse.click(at(1010, 270).x, at(1010, 270).y, { button: 'right' })
await page.waitForTimeout(300)
await page.screenshot({ path: '/tmp/pf/v4.png' })
await page.keyboard.press('Escape')
log('status', await page.getByRole('status').first().textContent())
log(errors.join('\n'))
await browser.close()
