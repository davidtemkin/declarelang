import { launch, slideBox } from './common.mjs'
const { browser, page, errors } = await launch()
const decks = await (await fetch('http://127.0.0.1:8361/api/decks')).json()
const deck = decks.decks.find((d) => d.title === 'Quarterly review')
await page.goto('http://localhost:5173/d/' + deck.id)
await page.waitForTimeout(1000)
const { at } = await slideBox(page)
await page.mouse.dblclick(at(640, 100).x, at(640, 100).y)
await page.waitForTimeout(200)
console.log('editor?', await page.locator('[data-text-editor]').count(), 'active:', await page.evaluate(() => document.activeElement?.outerHTML.slice(0, 120)))
await page.screenshot({ path: '/tmp/pf/d1.png' })
await page.keyboard.press('Meta+a')
await page.keyboard.type('New title')
await page.waitForTimeout(200)
await page.screenshot({ path: '/tmp/pf/d2.png' })
console.log(errors.join('\n'))
await browser.close()
