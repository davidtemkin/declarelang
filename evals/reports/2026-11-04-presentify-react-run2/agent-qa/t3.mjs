import { launch, slideBox, drag, api } from './common.mjs'
const { browser, context, page, errors } = await launch()
const log = (...a) => console.log(...a)
await page.goto('http://localhost:5173/')
await page.getByRole('button', { name: 'New presentation' }).first().click()
await page.waitForURL(/\/d\//)
await page.waitForTimeout(600)
await page.keyboard.type('Interaction test')
await page.keyboard.press('Enter')
const deckId = page.url().split('/d/')[1]
const { at, s } = await slideBox(page)
const els = async () => (await api(`/api/decks/${deckId}/slides`)).slides
// rectangle
await page.keyboard.press('r')
await drag(page, at(100, 100), at(500, 300))
// rounded via handle: radius handle at (100+14/s, 100+14/s)
const rh = at(100 + 14 / s, 100 + 14 / s)
await drag(page, rh, { x: rh.x + 40 * s, y: rh.y + 40 * s })
await page.screenshot({ path: '/tmp/pf/u1.png' })
// resize from se handle to width 600
const se = at(500, 300)
await drag(page, se, at(700, 300))
// line
await page.keyboard.press('l')
await page.keyboard.down('Shift')
await drag(page, at(100, 500), at(600, 530))
await page.keyboard.up('Shift')
await page.screenshot({ path: '/tmp/pf/u2.png' })
await page.waitForTimeout(1500)
let sl = await els()
log(JSON.stringify(sl[0].elements.map(e => e.kind === 'line' ? [e.kind, e.x1, e.y1, e.x2, e.y2] : [e.kind, e.x, e.y, e.width, e.height, e.cornerRadius, e.keepProportions])))
// copy the rect, paste into a new slide
await page.mouse.click(at(300, 200).x, at(300, 200).y)
await page.keyboard.press('Meta+c')
await page.getByRole('button', { name: 'New slide' }).first().click()
await page.keyboard.press('Meta+v')
await page.waitForTimeout(1500)
sl = await els()
log('slide2', JSON.stringify(sl[1]?.elements.map(e => [e.kind, e.x, e.y, e.width])))
// offline
await context.route('http://127.0.0.1:8361/**', (r) => r.abort())
await page.keyboard.press('ArrowRight')
await page.waitForTimeout(2500)
log('offline status:', await page.getByRole('status').first().textContent())
await page.screenshot({ path: '/tmp/pf/u3.png' })
await context.unroute('http://127.0.0.1:8361/**')
await page.keyboard.press('Meta+s')
await page.waitForTimeout(2500)
log('back status:', await page.getByRole('status').first().textContent())
sl = await els()
log('slide2 after', JSON.stringify(sl[1]?.elements.map(e => [e.kind, e.x, e.y, e.width])))
log(errors.join('\n'))
await browser.close()
