import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs';
const API = 'http://127.0.0.1:8361';
const j = (r) => r.json();
const created = await j(await fetch(`${API}/api/decks`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ title: 'A very long presentation title that goes on and on, describing the entire quarterly business review for the northern region and beyond' }) }));
const id = created.deck.id;
for (let i = 0; i < 99; i++) await fetch(`${API}/api/decks/${id}/slides`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ background: i % 2 ? '#0E3B43' : '#FFFFFF' }) });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto('http://localhost:5199/');
await page.waitForTimeout(1200);
await page.screenshot({ path: '/tmp/pwscripts/x-list.png' });
await page.goto('http://localhost:5199/p/' + id);
await page.waitForTimeout(1200);
await page.keyboard.press('End');
await page.getByRole('option', { name: 'Slide 1', exact: true }).focus();
await page.keyboard.press('End');
await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/pwscripts/x-100.png' });
// draw a rounded rect and edit text
const slide = page.getByLabel('Slide', { exact: true });
const b = await slide.boundingBox(); const s = b.width / 1280; const P = (x, y) => [b.x + x * s, b.y + y * s];
await page.keyboard.press('r');
await page.mouse.move(...P(200, 200)); await page.mouse.down(); await page.mouse.move(...P(700, 500), { steps: 5 }); await page.mouse.up();
const rh = await page.locator('[data-handle=radius]').boundingBox();
await page.mouse.move(rh.x + rh.width / 2, rh.y + rh.height / 2); await page.mouse.down();
await page.mouse.move(rh.x + 40, rh.y + 40, { steps: 5 });
await page.screenshot({ path: '/tmp/pwscripts/x-radius.png' });
await page.mouse.up();
console.log('radius', await page.getByLabel('Radius', { exact: true }).inputValue());
// widen rect, radius remains
const e = await page.locator('[data-handle=e]').boundingBox();
await page.mouse.move(e.x + 9, e.y + 9); await page.mouse.down(); await page.mouse.move(e.x + 150, e.y + 9, { steps: 5 }); await page.mouse.up();
console.log('radius after resize', await page.getByLabel('Radius', { exact: true }).inputValue(), 'W', await page.getByLabel('W', { exact: true }).inputValue());
await page.keyboard.press('t');
await page.mouse.click(...P(800, 300));
await page.keyboard.type('Editing text that wraps across more than one line of the box');
await page.screenshot({ path: '/tmp/pwscripts/x-editing.png' });
await page.keyboard.press('Escape');
await page.screenshot({ path: '/tmp/pwscripts/x-edited.png' });
console.log(errors.join('\n'));
console.log('deck', id);
await browser.close();
