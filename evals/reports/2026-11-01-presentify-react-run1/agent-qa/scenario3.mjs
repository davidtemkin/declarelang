import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs';
const deck = process.argv[2];
const API = 'http://127.0.0.1:8361';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ': ' + m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
const shot = (n) => page.screenshot({ path: `/tmp/pwscripts/${n}.png` });
await page.goto('http://localhost:5199/p/' + deck);
await page.waitForTimeout(1000);
const slide = page.getByLabel('Slide', { exact: true });
const b = await slide.boundingBox();
const s = b.width / 1280;
const P = (x, y) => [b.x + x * s, b.y + y * s];
// label next to circle (circle at ~ 340..460, 540..660)
await page.keyboard.press('t');
await page.mouse.click(...P(480, 580));
await page.keyboard.type('Label');
await page.keyboard.press('Escape');
await page.keyboard.down('Shift');
await page.mouse.click(...P(400, 600));
await page.keyboard.up('Shift');
console.log('header', await page.locator('.inspector-header').innerText());
await page.keyboard.press('Meta+g');
console.log('after group', await page.locator('.inspector-header').innerText());
await page.mouse.move(...P(400, 600)); await page.mouse.down();
await page.mouse.move(...P(500, 500), { steps: 10 }); await page.mouse.up();
await page.keyboard.press('Meta+z');
await page.keyboard.press('Meta+z');
console.log('after 2 undos', await page.locator('.inspector-header').innerText());
await shot('c0');
// colleague edits slide 2
const deckJson = await (await fetch(`${API}/api/decks/${deck}`)).json();
const s2id = deckJson.slideOrder[1];
const s2 = await (await fetch(`${API}/api/slides/${s2id}`)).json();
const el = s2.elements.find((e) => e.kind === 'text');
el.text.content = 'Colleague was here';
const put = await fetch(`${API}/api/slides/${s2id}`, { method: 'PUT', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ version: s2.version, background: '#FFF4E0', elements: s2.elements }) });
console.log('colleague put', put.status);
await page.getByRole('option', { name: 'Slide 2' }).click();
await page.waitForTimeout(800);
await shot('c1');
console.log('banner', await page.locator('.banner').innerText().catch(() => 'none'));
await page.getByRole('button', { name: 'Use their version' }).click();
await page.waitForTimeout(300);
await shot('c2');
// offline test
await page.route('http://127.0.0.1:8361/**', (r) => r.abort());
await page.keyboard.press('r');
await page.mouse.move(...P(900, 450)); await page.mouse.down(); await page.mouse.move(...P(1100, 600), { steps: 5 }); await page.mouse.up();
await page.waitForTimeout(2500);
console.log('offline status', await page.locator('.save-status').innerText());
await shot('c3');
await page.unroute('http://127.0.0.1:8361/**');
await page.waitForTimeout(4000);
console.log('back status', await page.locator('.save-status').innerText());
const after = await (await fetch(`${API}/api/slides/${s2id}`)).json();
console.log('slide2 elements', after.elements.map((e) => e.kind).join(','), after.background);
console.log(errors.join('\n'));
await browser.close();
