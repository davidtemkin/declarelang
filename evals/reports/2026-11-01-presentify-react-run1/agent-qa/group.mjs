import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs';
const deck = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
const shot = (n) => page.screenshot({ path: `/tmp/pwscripts/${n}.png` });
await page.goto('http://localhost:5199/p/' + deck);
await page.waitForTimeout(1000);
await page.getByRole('option', { name: 'Slide 2' }).click();
const slide = page.getByLabel('Slide', { exact: true });
const b = await slide.boundingBox();
const s = b.width / 1280;
const P = (x, y) => [b.x + x * s, b.y + y * s];
await page.mouse.click(...P(260, 560)); // circle
console.log('1', await page.locator('.inspector-header').innerText());
await page.keyboard.press('t');
await page.mouse.click(...P(340, 545));
await page.keyboard.type('Label');
await page.keyboard.press('Escape');
await page.keyboard.down('Shift');
await page.mouse.click(...P(260, 560));
await page.keyboard.up('Shift');
console.log('2', await page.locator('.inspector-header').innerText());
await page.getByRole('button', { name: 'Group', exact: true }).click();
console.log('3', await page.locator('.inspector-header').innerText());
await page.mouse.move(...P(260, 560)); await page.mouse.down();
await page.mouse.move(...P(500, 400), { steps: 10 });
await shot('m1');
await page.mouse.up();
await page.mouse.dblclick(...P(500 - 60, 400));
console.log('4 dbl', await page.locator('.inspector-header').innerText());
await page.keyboard.press('Escape');
await page.keyboard.press('Meta+z');
await page.keyboard.press('Meta+z');
console.log('5 undo', await page.locator('.inspector-header').innerText());
await shot('m2');
// resize the circle with a handle, check stays round
await page.mouse.click(...P(260, 560));
const knob = page.locator('[data-handle=e]');
const kb = await knob.boundingBox();
await page.mouse.move(kb.x + kb.width / 2, kb.y + kb.height / 2); await page.mouse.down();
await page.mouse.move(kb.x + 100, kb.y + kb.height / 2, { steps: 6 }); await page.mouse.up();
console.log('W/H', await page.getByLabel('W', { exact: true }).inputValue(), await page.getByLabel('H', { exact: true }).inputValue());
await shot('m3');
console.log(errors.join('\n'));
await browser.close();
