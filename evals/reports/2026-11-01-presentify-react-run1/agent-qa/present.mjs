import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto('http://localhost:5199/p/' + process.argv[2]);
await page.waitForTimeout(1000);
await page.getByRole('button', { name: 'Slide', exact: true }).click();
await page.getByRole('menuitem', { name: 'Present from Start' }).click();
await page.waitForTimeout(400);
console.log('presenting', await page.locator('.presenter').getAttribute('aria-label'), 'fs', await page.evaluate(() => !!document.fullscreenElement));
await page.keyboard.press('Space');
await page.mouse.click(700, 400);
await page.waitForTimeout(200);
console.log('now', await page.locator('.presenter').getAttribute('aria-label'));
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
console.log('after esc presenter count', await page.locator('.presenter').count(), 'current', await page.locator('[role=option][aria-selected=true]').getAttribute('aria-label'));
console.log(errors.join('\n'));
await browser.close();
