import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs';
const deck = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto('http://localhost:5199/p/' + deck);
await page.waitForTimeout(1000);
const slide = page.getByLabel('Slide', { exact: true });
const b = await slide.boundingBox(); const s = b.width / 1280; const P = (x, y) => [b.x + x * s, b.y + y * s];
await page.keyboard.press('l');
await page.mouse.move(...P(100, 650)); await page.mouse.down(); await page.mouse.move(...P(600, 690), { steps: 5 });
await page.keyboard.down('Shift'); await page.mouse.move(...P(600, 655), { steps: 2 }); await page.mouse.up(); await page.keyboard.up('Shift');
console.log('line handles', await page.locator('[data-handle^=end]').count(), 'header', await page.locator('.inspector-header').innerText());
await page.keyboard.press('Shift+ArrowRight');
await page.keyboard.press('ArrowDown');
console.log('X Y', await page.getByLabel('X', { exact: true }).inputValue(), await page.getByLabel('Y', { exact: true }).inputValue());
await page.keyboard.press('Meta+c');
await page.getByRole('option', { name: 'Slide 1', exact: true }).click();
await page.keyboard.press('Meta+v');
console.log('pasted header', await page.locator('.inspector-header').innerText(), 'X', await page.getByLabel('X', { exact: true }).inputValue());
await page.keyboard.press('Escape');
console.log('after esc', await page.locator('.inspector-header').innerText());
// context menu
await page.mouse.click(...P(130, 668), { button: 'right' });
await page.waitForTimeout(200);
await page.screenshot({ path: '/tmp/pwscripts/y-ctx.png' });
await page.keyboard.press('Escape');
await page.keyboard.press('Meta+z');
console.log('after undo paste', await page.locator('.inspector-header').innerText());
console.log(errors.join('\n'));
await browser.close();
