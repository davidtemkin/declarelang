import { chromium } from '/tmp/pw/node_modules/playwright/index.mjs';
const deck = process.argv[2];
const API = 'http://127.0.0.1:8361';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
let page = await ctx.newPage();
await page.goto('http://localhost:5199/p/' + deck);
await page.waitForTimeout(1000);
await page.route('http://127.0.0.1:8361/**', (r) => r.abort());
const slide = page.getByLabel('Slide', { exact: true });
const b = await slide.boundingBox(); const s = b.width / 1280; const P = (x, y) => [b.x + x * s, b.y + y * s];
await page.keyboard.press('o');
await page.mouse.move(...P(900, 100)); await page.mouse.down(); await page.mouse.move(...P(1000, 200), { steps: 4 }); await page.mouse.up();
await page.getByRole('button', { name: 'New Slide', exact: true }).first().click();
await page.waitForTimeout(1500);
console.log('status', await page.locator('.save-status').innerText());
await page.close();
page = await ctx.newPage();
await page.goto('http://localhost:5199/p/' + deck);
await page.waitForTimeout(3000);
console.log('status after reopen', await page.locator('.save-status').innerText());
const d = await (await fetch(`${API}/api/decks/${deck}/slides`)).json();
console.log('slides', d.slides.length, 'first slide kinds', d.slides[0].elements.map((e) => e.kind).join(','));
console.log('backup left', await page.evaluate((id) => localStorage.getItem('presentify.unsaved.' + id), deck));
await browser.close();
