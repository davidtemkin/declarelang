import { chromium, devices } from "playwright"
const b = await chromium.launch()
const phone = await (await b.newContext({ ...devices["iPhone 13"] })).newPage()
await phone.goto("http://127.0.0.1:8200/my-apps/venue/venue.declare"); await phone.waitForTimeout(1500)
await phone.screenshot({ path: "/tmp/s-phone-list.png" })
await phone.getByRole("button", { name: /^Sat 21 Nov/ }).click(); await phone.waitForTimeout(1500)
const id = await phone.evaluate(() => [...document.querySelectorAll('[aria-pressed="false"]')].find((e) => e.getAttribute("aria-disabled") != "true").getAttribute("aria-label"))
await phone.getByRole("button", { name: id, exact: true }).click()
await phone.getByRole("button", { name: "Continue" }).click(); await phone.waitForTimeout(600)
await phone.getByLabel("Card number").pressSequentially("4000000000000002")
await phone.getByLabel("Expiry").focus(); await phone.waitForTimeout(300)
await phone.screenshot({ path: "/tmp/s-phone-checkout.png" })
await phone.getByRole("button", { name: "Sign in" }).first().click(); await phone.waitForTimeout(800)
await phone.screenshot({ path: "/tmp/s-phone-signin.png" })
await b.close()
