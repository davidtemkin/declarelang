import { chromium, devices } from "playwright"
const b = await chromium.launch(); const page = await (await b.newContext({ ...devices["iPhone 13"] })).newPage()
page.on("pageerror", (e) => console.log("PAGE ERROR", e.message))
await page.goto("http://127.0.0.1:8200/my-apps/venue/venue.declare#p03")
await page.getByText(/seats free/).first().waitFor(); await page.waitForTimeout(600)
const id = await page.evaluate(() => [...document.querySelectorAll('[aria-pressed="false"]')].find((e) => e.getAttribute("aria-disabled") != "true").getAttribute("aria-label"))
await page.getByRole("button", { name: id, exact: true }).click()
await page.getByRole("button", { name: "Continue" }).click(); await page.waitForTimeout(400)
await page.getByRole("button", { name: "Sign in" }).first().click()
await page.getByLabel("Email").first().fill("ada@example.com"); await page.getByLabel("Password").fill("correct horse battery")
await page.getByRole("button", { name: "Sign in" }).last().click(); await page.waitForTimeout(1500)
const rd = () => page.evaluate(() => { const d = window.__declare.find("app.draft"); return [d.payWith, d.usingSaved, d.savedCard?.id ?? null] })
console.log("signed in", await rd())
await page.getByRole("radio", { name: "A new card" }).click(); await page.waitForTimeout(300)
console.log("new", await rd())
console.log(JSON.stringify(await page.evaluate(() => window.__declare.explain("app.draft", "savedCard"))))
console.log("email fields:", await page.getByLabel("Email").count(), "saved cvc:", await page.getByLabel("Security code").count())
console.log(await page.evaluate(() => { const f = window.__declare.find("app.payForm"); return [f.card != null, f.how?.saved != null] }))
await b.close()
