// End-to-end flows against the running app and service, found by role and name.
// node flow.mjs [desk|phone]
import { chromium, devices } from "playwright"

const URL = "http://127.0.0.1:8200/my-apps/venue/venue.declare"
const mode = process.argv[2] ?? "desk"
const browser = await chromium.launch()
const ctx = mode == "phone"
    ? await browser.newContext({ ...devices["iPhone 13"] })
    : await browser.newContext({ viewport: { width: 1280, height: 800 } })
const page = await ctx.newPage()
const posts = []
page.on("response", (r) => { if (r.request().method() == "POST") { posts.push(r.url()); console.log("   POST", r.url().split("/api")[1], r.status(), Date.now() % 100000) } })
page.on("pageerror", (e) => console.log("PAGE ERROR", e.message))
page.on("console", (m) => { if (m.type() == "error" && !m.text().includes("401")) console.log("console:", m.text()) })

const ok = (cond, what) => console.log((cond ? "  ✓ " : "  ✗ ") + what)
const shot = (n) => page.screenshot({ path: `/tmp/flow-${mode}-${n}.png` })

async function freeSeats(section, n) {
    return page.evaluate(([section, n]) => [...document.querySelectorAll('[aria-pressed="false"]')]
        .filter((e) => e.getAttribute("aria-disabled") != "true")
        .map((e) => e.getAttribute("aria-label"))
        .filter((l) => l && l.startsWith(section + ", row")).slice(0, n), [section, n])
}

await page.goto(URL)
await page.getByRole("button", { name: /^Fri 13 Nov/ }).click()
await page.getByText(/seats free/).first().waitFor()
await page.waitForTimeout(800)

const orch = await freeSeats("Orchestra", 2)
const gt = await freeSeats("Grand Tier", 1)
for (const s of [...orch, ...gt]) await page.getByRole("button", { name: s, exact: true }).click()
await page.waitForTimeout(400)
ok(await page.getByText("3 seats · $225.00").first().isVisible(), "summary reads 3 seats · $225.00")
await shot("1-chosen")
await page.getByRole("button", { name: gt[0], exact: true }).click()
ok(await page.getByText("2 seats · $160.00").first().isVisible(), "unchoosing updates the total")
await page.getByRole("button", { name: gt[0], exact: true }).click()

await page.getByRole("button", { name: "Continue" }).first().click()
await page.waitForTimeout(500)

if (mode == "phone") {
    // sign in midway, use the saved Visa, be declined, then pay with a new card
    await page.getByRole("button", { name: "Sign in" }).first().click()
    await page.getByLabel("Email").fill("ada@example.com")
    await page.getByLabel("Password").fill("wrong")
    await page.getByRole("button", { name: "Sign in" }).last().click()
    await page.waitForTimeout(800)
    ok(await page.getByText("That email and password don't match.").isVisible(), "wrong password: the service's sentence")
    await page.getByLabel("Password").fill("correct horse battery")
    await page.getByRole("button", { name: "Sign in" }).last().click()
    await page.waitForTimeout(1500)
    await shot("2-signed-in")
    ok(await page.getByRole("radio", { name: /Visa ending 4242/ }).isChecked(), "Visa 4242 offered and chosen")
    ok(await page.getByRole("radio", { name: /Mastercard ending 4444/ }).isDisabled(), "expired Mastercard cannot be chosen")
    await page.getByLabel("Security code").first().fill("000")
    await page.getByRole("button", { name: "Pay $245.00" }).click()
    await page.waitForTimeout(2500)
    await shot("3-declined")
    const declined = await page.getByRole("status").allInnerTexts()
    console.log("   said:", declined.join(" | "))
    await page.getByRole("radio", { name: "A new card" }).click()
    await page.waitForTimeout(300)
    await shot("3b-newcard")
    console.log("   new card checked:", await page.getByRole("radio", { name: "A new card" }).isChecked())
    ok(await page.getByLabel("Email").inputValue() == "ada@example.com", "email filled from the account")
    await page.getByLabel("Card number").pressSequentially("5555555555554444")
    ok(await page.getByLabel("Card number").inputValue() == "5555 5555 5555 4444", "number grouped")
    await page.getByLabel("Expiry").pressSequentially("1230")
    await page.getByLabel("Security code").fill("123")
    await page.getByLabel("Postal code").fill("WC1N 1A")
    await page.getByLabel("City").focus()
    await page.waitForTimeout(300)
    ok(await page.getByText("Enter a postcode like SW1A 1AA.").isVisible(), "bad postcode caught on leaving")
    await shot("4-postcode")
    await page.getByLabel("Postal code").fill("WC1N 1AB")
    await page.getByRole("button", { name: "Pay $245.00" }).dblclick()
    await page.waitForTimeout(3000)
} else {
    await page.getByRole("button", { name: "Pay $245.00" }).click()
    await page.waitForTimeout(400)
    await shot("2-empty-pay")
    ok(await page.getByText("Enter the card number.").isVisible(), "required fields shown on Pay")
    await page.getByLabel("Email").fill("kim@example.com")
    await page.getByLabel("Name on card").fill("Kim Lee")
    await page.getByLabel("Card number").pressSequentially("378282246310005")
    ok(await page.getByLabel("Card number").inputValue() == "3782 822463 10005", "amex grouped 4-6-5")
    await page.getByLabel("Expiry").pressSequentially("1330")
    await page.getByLabel("Security code").focus()
    ok(await page.getByText("That month isn't one").isVisible(), "a month that isn't one is caught")
    await page.getByLabel("Expiry").fill("")
    await page.getByLabel("Expiry").pressSequentially("0429")
    await page.getByLabel("Security code").fill("1234")
    await page.getByRole("radio", { name: "United States" }).click()
    await page.getByLabel("Street address").fill("1 Main St")
    await page.getByLabel("City").fill("Springfield")
    await page.getByLabel("Postal code").fill("10001")
    await page.getByRole("button", { name: "Pay $245.00" }).click()
    await page.waitForTimeout(2500)
    await shot("3-postal-refused")
    const focused = await page.evaluate(() => document.activeElement?.getAttribute("aria-label") ?? document.activeElement?.name)
    console.log("   focus after 422:", focused)
    await page.getByLabel("Postal code").fill("94110")
    await page.keyboard.press("Enter")
    await page.keyboard.press("Enter")
    await page.waitForTimeout(3000)
}
await shot("5-tickets")
ok(await page.getByText(/^Sent to /).isVisible(), "tickets: " + (await page.getByText(/^Sent to /).innerText().catch(() => "?")))
console.log("   orders posted:", posts.filter((p) => p.includes("/api/orders")).length)
await browser.close()
