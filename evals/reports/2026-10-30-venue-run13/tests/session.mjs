import { chromium } from "playwright"
const ok = (c, w) => console.log((c ? "  ✓ " : "  ✗ ") + w)
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } }); const page = await ctx.newPage()
page.on("pageerror", (e) => console.log("PAGE ERROR", e.message))
await page.goto("http://127.0.0.1:8200/my-apps/venue/venue.declare")
await page.getByRole("button", { name: "Sign in" }).click()
await page.getByLabel("Email").fill("a@a.co"); await page.getByLabel("Password").fill("pass")
ok(await page.getByLabel("Password").getAttribute("type") == "password", "password hidden")
await page.getByRole("checkbox", { name: "Show password" }).click()
ok(await page.getByLabel("Password").getAttribute("type") == "text", "show password reveals")
console.log("   autocomplete:", await page.getByLabel("Email").getAttribute("autocomplete"), await page.getByLabel("Password").getAttribute("autocomplete"))
await page.getByLabel("Password").press("Enter"); await page.waitForTimeout(1200)
ok(await page.getByRole("button", { name: "Sign out" }).isVisible(), "signed in")
await page.reload(); await page.waitForTimeout(1500)
ok(await page.getByRole("button", { name: "Sign out" }).isVisible(), "reload keeps the session")
await page.getByRole("button", { name: /^Fri 13 Nov/ }).click(); await page.waitForTimeout(1200)
const id = await page.evaluate(() => [...document.querySelectorAll('[aria-pressed="false"]')].find((e) => e.getAttribute("aria-disabled") != "true").getAttribute("aria-label"))
await page.getByRole("button", { name: id, exact: true }).click()
await page.getByRole("button", { name: "Continue" }).click(); await page.waitForTimeout(400)
ok(await page.getByRole("heading", { name: "Checkout" }).isVisible(), "at checkout")
await page.goBack(); await page.waitForTimeout(600)
ok(await page.getByText("1 seat · ").isVisible(), "Back returns to the hall, choice intact")
await page.goBack(); await page.waitForTimeout(600)
ok(await page.getByRole("heading", { name: "The Marriage of Figaro" }).isVisible(), "Back again: the season")
await page.getByRole("button", { name: "Sign out" }).click(); await page.waitForTimeout(800)
ok(await page.getByRole("button", { name: "Sign in" }).isVisible(), "signed out")
await page.reload(); await page.waitForTimeout(1500)
ok(await page.getByRole("button", { name: "Sign in" }).isVisible(), "still signed out after reload")
await b.close()
