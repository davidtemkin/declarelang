import { chromium } from "playwright"
const b = await chromium.launch(); const page = await (await b.newContext({ viewport: { width: 1280, height: 800 } })).newPage()
page.on("pageerror", (e) => console.log("PAGE ERROR", e.message))
await page.goto("http://127.0.0.1:8200/my-apps/venue/venue.declare#p02")
await page.getByText(/seats free/).first().waitFor(); await page.waitForTimeout(600)
const id = await page.evaluate(() => [...document.querySelectorAll('[aria-pressed="false"]')].find((e) => e.getAttribute("aria-disabled") != "true").getAttribute("aria-label"))
await page.getByRole("button", { name: id, exact: true }).click()
await page.getByRole("button", { name: "Continue" }).click(); await page.waitForTimeout(400)
await page.getByLabel("Email").fill("kim@example.com"); await page.getByLabel("Name on card").fill("Kim")
await page.getByLabel("Card number").fill("4242424242424242"); await page.getByLabel("Expiry").fill("0429")
await page.getByLabel("Security code").fill("123"); await page.getByLabel("Street address").fill("1 Main")
await page.getByLabel("City").fill("NYC"); await page.getByLabel("Postal code").fill("10001")
const pay = page.getByRole("button", { name: /^Pay / }); await pay.click()
await page.waitForTimeout(2500)
console.log(await page.evaluate(() => document.activeElement?.outerHTML?.slice(0, 200)))
console.log(await page.getByLabel("Postal code").getAttribute("aria-description"))
await page.screenshot({ path: "/tmp/dbg422.png" })
await b.close()
